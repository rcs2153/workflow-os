test("final admission rejects source, dirtiness, version, binary, and target drift", { skip: !nativeTarget }, () => {
  const sourceMismatch = nativeFixture();
  assert.throws(
    () =>
      packageRelease({
        projectDir: sourceMismatch.projectDir,
        binaryPath: sourceMismatch.binaryPath,
        outputDir: join(sourceMismatch.directory, "output"),
        target: sourceMismatch.target,
        sourceCommit: "a".repeat(40),
        posture: releasePackagePostures.finalCandidate,
      }),
    /source commit mismatch/,
  );
  assert.equal(existsSync(join(sourceMismatch.directory, "output")), false);

  const dirty = nativeFixture();
  writeFileSync(join(dirty.projectDir, "untracked"), "dirty\n");
  assert.throws(
    () =>
      packageRelease({
        projectDir: dirty.projectDir,
        binaryPath: dirty.binaryPath,
        outputDir: join(dirty.directory, "output"),
        target: dirty.target,
        sourceCommit: dirty.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /clean exact source checkout/,
  );

  const versionDrift = nativeFixture();
  const lockPath = join(versionDrift.projectDir, "package-lock.json");
  const lock = JSON.parse(readFileSync(lockPath, "utf8"));
  lock.packages["packages/sdk-typescript"].version = "9.9.9";
  writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
  assert.throws(
    () =>
      packageRelease({
        projectDir: versionDrift.projectDir,
        binaryPath: versionDrift.binaryPath,
        outputDir: join(versionDrift.directory, "output"),
        target: versionDrift.target,
        sourceCommit: versionDrift.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /release version mismatch/,
  );

  const cargoLockDrift = nativeFixture();
  const cargoLockPath = join(cargoLockDrift.projectDir, "Cargo.lock");
  writeFileSync(
    cargoLockPath,
    readFileSync(cargoLockPath, "utf8").replace(
      'name = "workflow-core"\nversion = "0.4.0-preview.1"',
      'name = "workflow-core"\nversion = "9.9.9"',
    ),
  );
  assert.throws(
    () =>
      packageRelease({
        projectDir: cargoLockDrift.projectDir,
        binaryPath: cargoLockDrift.binaryPath,
        outputDir: join(cargoLockDrift.directory, "output"),
        target: cargoLockDrift.target,
        sourceCommit: cargoLockDrift.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /release version mismatch/,
  );

  const binaryDrift = nativeFixture("9.9.9");
  assert.throws(
    () =>
      packageRelease({
        projectDir: binaryDrift.projectDir,
        binaryPath: binaryDrift.binaryPath,
        outputDir: join(binaryDrift.directory, "output"),
        target: binaryDrift.target,
        sourceCommit: binaryDrift.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /binary version mismatch/,
  );

  const binaryShapeDrift = nativeFixture();
  writeFileSync(binaryShapeDrift.binaryPath, `#!/bin/sh\necho 'workflow-os ${version}'\n`, "utf8");
  chmodSync(binaryShapeDrift.binaryPath, 0o755);
  assert.throws(
    () =>
      packageRelease({
        projectDir: binaryShapeDrift.projectDir,
        binaryPath: binaryShapeDrift.binaryPath,
        outputDir: join(binaryShapeDrift.directory, "output"),
        target: binaryShapeDrift.target,
        sourceCommit: binaryShapeDrift.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /binary does not match target/,
  );

  const targetDrift = nativeFixture();
  const otherTarget = nativeTarget === "aarch64-apple-darwin" ? "x86_64-unknown-linux-musl" : "aarch64-apple-darwin";
  assert.throws(
    () =>
      packageRelease({
        projectDir: targetDrift.projectDir,
        binaryPath: targetDrift.binaryPath,
        outputDir: join(targetDrift.directory, "output"),
        target: otherTarget,
        sourceCommit: targetDrift.sourceCommit,
        posture: releasePackagePostures.finalCandidate,
      }),
    /must be packaged on its native host/,
  );
});
