import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import test from "node:test";

import { packageRelease, releasePackagePostures } from "./package-release.mjs";

const sourceProjectDir = resolve(import.meta.dirname, "..");
const packageScript = join(sourceProjectDir, "scripts/package-release.mjs");
const version = JSON.parse(readFileSync(join(sourceProjectDir, "package.json"), "utf8")).version;
const provisionalSourceCommit = "0123456789abcdef0123456789abcdef01234567";
const nativeTarget =
  process.platform === "darwin" && process.arch === "arm64"
    ? "aarch64-apple-darwin"
    : process.platform === "linux" && process.arch === "x64"
      ? "x86_64-unknown-linux-musl"
      : null;

function provisionalFixture() {
  const directory = mkdtempSync(join(tmpdir(), "workflow-os-package-"));
  const binaryPath = join(directory, "workflow-os");
  writeFileSync(binaryPath, `#!/bin/sh\necho 'workflow-os ${version}'\n`, "utf8");
  chmodSync(binaryPath, 0o755);
  return { directory, binaryPath };
}

function writeReleaseIdentityProject(projectDir) {
  const crates = ["workflow-cli", "workflow-core", "workflow-hosted", "workflow-local-host"];
  for (const crate of crates) {
    const crateDir = join(projectDir, "crates", crate);
    mkdirSync(crateDir, { recursive: true });
    writeFileSync(join(crateDir, "Cargo.toml"), `[package]\nname = "${crate}"\nversion = "${version}"\n`);
  }
  mkdirSync(join(projectDir, "packages/sdk-typescript"), { recursive: true });
  writeFileSync(join(projectDir, "package.json"), `${JSON.stringify({ name: "workflow-os", version }, null, 2)}\n`);
  writeFileSync(
    join(projectDir, "packages/sdk-typescript/package.json"),
    `${JSON.stringify({ name: "@workflow-os/sdk-typescript", version }, null, 2)}\n`,
  );
  writeFileSync(
    join(projectDir, "package-lock.json"),
    `${JSON.stringify(
      {
        name: "workflow-os",
        version,
        lockfileVersion: 3,
        packages: {
          "": { name: "workflow-os", version },
          "packages/sdk-typescript": { name: "@workflow-os/sdk-typescript", version },
        },
      },
      null,
      2,
    )}\n`,
  );
  writeFileSync(
    join(projectDir, "Cargo.lock"),
    [
      "# This file is automatically @generated by Cargo.",
      "version = 4",
      ...crates.flatMap((crate) => ["", "[[package]]", `name = "${crate}"`, `version = "${version}"`]),
      "",
    ].join("\n"),
  );
  writeFileSync(join(projectDir, "LICENSE"), readFileSync(join(sourceProjectDir, "LICENSE")));
  writeFileSync(join(projectDir, "README.md"), "# Workflow OS release fixture\n");
}

function nativeFixture(binaryVersion = version) {
  if (!nativeTarget) {
    throw new Error(`unsupported test host: ${process.platform}/${process.arch}`);
  }
  const directory = mkdtempSync(join(tmpdir(), "workflow-os-final-package-"));
  const projectDir = join(directory, "project");
  mkdirSync(projectDir);
  writeReleaseIdentityProject(projectDir);
  execFileSync("git", ["init", "--quiet"], { cwd: projectDir });
  execFileSync("git", ["config", "user.name", "Workflow OS Test"], { cwd: projectDir });
  execFileSync("git", ["config", "user.email", "test@workflowos.dev"], { cwd: projectDir });
  execFileSync("git", ["add", "."], { cwd: projectDir });
  execFileSync("git", ["commit", "--quiet", "-m", "release fixture"], { cwd: projectDir });
  const sourceCommit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: projectDir, encoding: "utf8" }).trim();
  const sourcePath = join(directory, "workflow-os.c");
  const binaryPath = join(directory, "workflow-os");
  writeFileSync(sourcePath, `#include <stdio.h>\nint main(void) { puts("workflow-os ${binaryVersion}"); return 0; }\n`);
  const compilerArguments =
    process.platform === "linux"
      ? ["-static", sourcePath, "-o", binaryPath]
      : [sourcePath, "-o", binaryPath];
  execFileSync("cc", compilerArguments);
  return { directory, projectDir, binaryPath, sourceCommit, target: nativeTarget };
}

function packageProvisional(outputDir, binaryPath) {
  return packageRelease({
    projectDir: sourceProjectDir,
    binaryPath,
    outputDir,
    target: "aarch64-apple-darwin",
    sourceCommit: provisionalSourceCommit,
    posture: releasePackagePostures.provisionalRehearsal,
    verifyBinary: false,
    verifyRepository: false,
  });
}

test("requires one explicit closed package posture", () => {
  const { directory, binaryPath } = provisionalFixture();
  const base = {
    projectDir: sourceProjectDir,
    binaryPath,
    outputDir: directory,
    target: "aarch64-apple-darwin",
    sourceCommit: provisionalSourceCommit,
    verifyBinary: false,
    verifyRepository: false,
  };
  assert.throws(() => packageRelease(base), /posture must be exactly one of/);
  assert.throws(() => packageRelease({ ...base, posture: "final" }), /posture must be exactly one of/);

  const completeCli = [
    packageScript,
    "--binary",
    binaryPath,
    "--output-dir",
    join(directory, "cli"),
    "--source-commit",
    provisionalSourceCommit,
    "--target",
    "aarch64-apple-darwin",
  ];
  const missing = spawnSync(process.execPath, completeCli, { encoding: "utf8" });
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /exactly one release package posture is required/);
  assert.equal(existsSync(join(directory, "cli")), false);

  const conflicting = spawnSync(process.execPath, [...completeCli, "--provisional", "--final-candidate"], {
    encoding: "utf8",
  });
  assert.equal(conflicting.status, 1);
  assert.match(conflicting.stderr, /posture flags are mutually exclusive/);
  assert.equal(existsSync(join(directory, "cli")), false);
});

test("produces deterministic provisional v1 archives and checksums", () => {
  const { directory, binaryPath } = provisionalFixture();
  const first = packageProvisional(join(directory, "first"), binaryPath);
  const second = packageProvisional(join(directory, "second"), binaryPath);
  assert.equal(first.checksum, second.checksum);
  assert.deepEqual(readFileSync(first.archivePath), readFileSync(second.archivePath));
  assert.equal(first.manifest.schema_version, "workflowos.dev/release-package/v1");
  assert.equal(first.manifest.posture, releasePackagePostures.provisionalRehearsal);
  assert.equal(first.manifest.working_tree_clean, false);
  assert.match(readFileSync(`${first.archivePath}.sha256`, "utf8"), new RegExp(`^${first.checksum}  `));
});

test("refuses to overwrite an archive or checksum", () => {
  const { directory, binaryPath } = provisionalFixture();
  const outputDir = join(directory, "output");
  const result = packageProvisional(outputDir, binaryPath);
  assert.throws(() => packageProvisional(outputDir, binaryPath), /release output already exists/);
  assert.equal(readFileSync(result.archivePath).length > 0, true);

  const checksumOnlyDir = join(directory, "checksum-only");
  mkdirSync(checksumOnlyDir);
  const archiveName = `workflow-os-v${version}-aarch64-apple-darwin.tar.gz`;
  const checksumPath = join(checksumOnlyDir, `${archiveName}.sha256`);
  writeFileSync(checksumPath, "user-owned checksum\n");
  assert.throws(() => packageProvisional(checksumOnlyDir, binaryPath), /release output already exists/);
  assert.equal(readFileSync(checksumPath, "utf8"), "user-owned checksum\n");
  assert.equal(existsSync(join(checksumOnlyDir, archiveName)), false);
});

test("archive installs, refuses overwrite, and uninstalls only the binary", () => {
  const { directory, binaryPath } = provisionalFixture();
  const result = packageProvisional(join(directory, "output"), binaryPath);
  const extractDir = join(directory, "extract");
  mkdirSync(extractDir);
  execFileSync("tar", ["-xzf", result.archivePath, "-C", extractDir]);
  const root = join(extractDir, `workflow-os-v${version}-aarch64-apple-darwin`);
  const installDir = join(directory, "install");
  const stateDir = join(directory, ".workflow-os");
  mkdirSync(stateDir);
  writeFileSync(join(stateDir, "state"), "preserve\n");
  execFileSync(join(root, "install.sh"), { env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir } });
  assert.equal(
    execFileSync(join(installDir, "workflow-os"), ["--version"], { encoding: "utf8" }).trim(),
    `workflow-os ${version}`,
  );
  assert.throws(() =>
    execFileSync(join(root, "install.sh"), { env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir } }),
  );
  assert.throws(() =>
    execFileSync(join(root, "install.sh"), ["--force", "extra"], {
      env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir },
    }),
  );
  execFileSync(join(root, "install.sh"), ["--force"], {
    env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir },
  });
  assert.equal(
    execFileSync(join(installDir, "workflow-os"), ["--version"], { encoding: "utf8" }).trim(),
    `workflow-os ${version}`,
  );
  execFileSync(join(root, "uninstall.sh"), { env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir } });
  execFileSync(join(root, "uninstall.sh"), { env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir } });
  assert.equal(existsSync(join(installDir, "workflow-os")), false);
  assert.equal(readFileSync(join(stateDir, "state"), "utf8"), "preserve\n");
});

test("installer rejects dangling destination symlinks without writing outside the install directory", () => {
  const { directory, binaryPath } = provisionalFixture();
  const result = packageProvisional(join(directory, "output"), binaryPath);
  const extractDir = join(directory, "extract");
  mkdirSync(extractDir);
  execFileSync("tar", ["-xzf", result.archivePath, "-C", extractDir]);
  const root = join(extractDir, `workflow-os-v${version}-aarch64-apple-darwin`);
  const installDir = join(directory, "install");
  const destination = join(installDir, "workflow-os");
  const outsideTarget = join(directory, "outside-workflow-os");
  mkdirSync(installDir);
  symlinkSync(outsideTarget, destination);

  for (const args of [[], ["--force"]]) {
    const result = spawnSync(join(root, "install.sh"), args, {
      encoding: "utf8",
      env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir },
    });
    assert.equal(result.status, 1);
    assert.match(result.stderr, /refusing destination symlink/);
    assert.equal(existsSync(outsideTarget), false);
    assert.equal(readlinkSync(destination), outsideTarget);
  }

  writeFileSync(outsideTarget, "preserve\n");
  for (const args of [[], ["--force"]]) {
    const result = spawnSync(join(root, "install.sh"), args, {
      encoding: "utf8",
      env: { ...process.env, WORKFLOW_OS_INSTALL_DIR: installDir },
    });
    assert.equal(result.status, 1);
    assert.match(result.stderr, /refusing destination symlink/);
    assert.equal(readFileSync(outsideTarget, "utf8"), "preserve\n");
    assert.equal(readlinkSync(destination), outsideTarget);
  }

  const installer = readFileSync(join(root, "install.sh"), "utf8");
  assert.match(installer, /mktemp/);
  assert.match(installer, /ln "\$\{temporary\}" "\$\{destination\}"/);
  assert.match(installer, /rm -f "\$\{destination\}"/);
  assert.doesNotMatch(installer, /mv .*"\$\{destination\}"/);
  assert.doesNotMatch(installer, /cp .*"\$\{destination\}"/);
});

